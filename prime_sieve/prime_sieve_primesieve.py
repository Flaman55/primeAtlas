LOW_FLOOR_CUTOFF = 7  # Duplicated from prime_sieve_v3.py -- see that file's own constant for
                      # the full rationale (floors 0-6 are each narrower than the smallest
                      # supported window_m, 10,000,000).


def _low_floor_segments(base_power, combined_lo, combined_hi):
    """Ported verbatim from prime_sieve_v3.py -- see that file's docstring for the full
    rationale (splits a low-floor combined range by REAL floor boundary instead of writing
    one window that numerically bleeds across several floors)."""
    if base_power >= LOW_FLOOR_CUTOFF or combined_lo != 10 ** base_power:
        return []
    segments = []
    floor = base_power
    while True:
        floor_lo = 10 ** floor
        floor_hi = 10 ** (floor + 1)
        if floor_hi > combined_hi:
            break
        segments.append((floor, floor_lo, floor_hi))
        floor += 1
    return segments


