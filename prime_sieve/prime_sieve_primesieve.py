# ------------------------------------------------------------------------------------------
# libprimesieve C API binding -- ctypes, straight against the SYSTEM-installed shared library
# (located via ctypes.util.find_library), NOT one of this project's own .c wrapper engines.
#
# primesieve_generate_primes(start, stop, &size, type) -- note the INCLUSIVE [start, stop]
# range (primesieve's own convention) vs. this project's usual EXCLUSIVE [lo, hi) convention
# used everywhere else in this codebase (windows, floors, combined ranges) -- the one call
# site below (generate_primes_in_range) converts explicitly at the boundary (stop = hi - 1)
# rather than silently mixing the two. Returns a malloc'd array of the requested type;
# primesieve_free() is called on it, after its contents are copied into a plain Python list,
# before this module hands control back to its caller -- nothing here keeps a reference to
# primesieve's own malloc'd memory past generate_primes_in_range() returning.
#
# Source: https://github.com/kimwalisch/primesieve -- include/primesieve.h and
# doc/C_API.md in that repository.
# ------------------------------------------------------------------------------------------

UINT64_PRIMES = 13  # enum value in primesieve.h -- 0-indexed by declaration order: SHORT=0
                     # USHORT=1 INT=2 UINT=3 LONG=4 ULONG=5 LONGLONG=6 ULONGLONG=7 INT16=8
                     # UINT16=9 INT32=10 UINT32=11 INT64=12 UINT64=13. UINT64 (not INT64) is
                     # required here -- floor 19 and above hold values past 2**63-1, which
                     # would silently overflow a signed 64-bit slot.

_lib = None


def _load_lib():
    global _lib
    if _lib is None:
        lib_path = ctypes.util.find_library("primesieve")
        if not lib_path:
            # find_library() can fail to locate an SONAME-versioned .so on some distros even
            # when the library is genuinely installed -- fall back to the plain unversioned
            # name a -dev package's linker script normally provides.
            lib_path = "libprimesieve.so"
        try:
            lib = ctypes.CDLL(lib_path, use_errno=True)
        except OSError as e:
            raise RuntimeError(
                f"Could not load libprimesieve ({lib_path}): {e}. Install it first (e.g. "
                f"'apt install libprimesieve-dev', or build from "
                f"https://github.com/kimwalisch/primesieve) -- this mode calls the system "
                f"library directly; unlike this project's other engines, it does not link "
                f"its own .c wrapper.") from e
        lib.primesieve_generate_primes.argtypes = [
            ctypes.c_uint64, ctypes.c_uint64, ctypes.POINTER(ctypes.c_size_t), ctypes.c_int]
        lib.primesieve_generate_primes.restype = ctypes.c_void_p
        lib.primesieve_free.argtypes = [ctypes.c_void_p]
        lib.primesieve_free.restype = None
        lib.primesieve_get_max_stop.argtypes = []
        lib.primesieve_get_max_stop.restype = ctypes.c_uint64
        lib.primesieve_version.argtypes = []
        lib.primesieve_version.restype = ctypes.c_char_p
        # count_primes/nth_prime -- added for PrimeAtlas's 'primesieve' calculator sub-tab
        # (Liczby pierwsze -> primesieve, see primesieve_query.py in this same folder for
        # the CLI entry point the GUI actually launches). Both are genuine sieve
        # operations under the hood (libprimesieve counts/searches by sieving the
        # requested range, not an O(1) formula), so a caller asking for a huge range
        # should expect real wall-clock cost, same as generate_primes_in_range() above.
        lib.primesieve_count_primes.argtypes = [ctypes.c_uint64, ctypes.c_uint64]
        lib.primesieve_count_primes.restype = ctypes.c_uint64
        lib.primesieve_nth_prime.argtypes = [ctypes.c_int64, ctypes.c_uint64]
        lib.primesieve_nth_prime.restype = ctypes.c_int64
        _lib = lib
    return _lib


def primesieve_max_stop():
    """The uint64_t ceiling libprimesieve itself reports (primesieve_get_max_stop()) --
    read directly from the library rather than hardcoded, so this stays correct even if a
    future primesieve version ever changes it. Currently always 2**64 - 1
    (18,446,744,073,709,551,615), which falls in the middle of floor 19, not at a floor
    boundary."""
    return int(_load_lib().primesieve_get_max_stop())


def primesieve_lib_version():
    return _load_lib().primesieve_version().decode("ascii")


def generate_primes_in_range(lo, hi):
    """Returns a sorted Python list of every prime in the EXCLUSIVE range [lo, hi) (this
    project's own convention) by calling primesieve_generate_primes(lo, hi - 1, ...)
    (primesieve's own INCLUSIVE convention) exactly once -- no batching, no chunking on the
    generation side, matching this mode's whole point (see module header).

    The returned buffer is copied into a plain Python list of native ints, then freed
    (primesieve_free) before this function returns.

    Caller is responsible for ensuring hi - 1 <= primesieve_max_stop() -- this function does
    not clamp; see generate_floor_windows()'s ceiling check, which is the one place that
    decision belongs (it also has to report the truncation to the user)."""
    if hi <= lo:
        return []
    lib = _load_lib()
    size = ctypes.c_size_t(0)
    ctypes.set_errno(0)
    ptr = lib.primesieve_generate_primes(lo, hi - 1, ctypes.byref(size), UINT64_PRIMES)
    if not ptr:
        errno = ctypes.get_errno()
        if errno != 0:
            raise RuntimeError(
                f"primesieve_generate_primes({lo}, {hi - 1}) failed (errno={errno})")
        return []
    try:
        arr = (ctypes.c_uint64 * size.value).from_address(ptr)
        primes = list(arr)
    finally:
        lib.primesieve_free(ptr)
    return primes


def count_primes_in_range(lo, hi):
    """Returns the COUNT of primes in the EXCLUSIVE range [lo, hi) (this project's own
    convention) via primesieve_count_primes(lo, hi - 1) (primesieve's own INCLUSIVE
    convention -- see generate_primes_in_range()'s own comment for the same lo/hi-1
    boundary conversion). Unlike generate_primes_in_range(), this never materializes the
    primes themselves -- libprimesieve counts by sieving internally without allocating an
    output array -- so it's the right call for 'how many primes in [a, b]' even when the
    range is far too wide to ever list, though it is still a genuine sieve pass under the
    hood (not an O(1) formula): a caller asking about a huge range should expect real
    wall-clock cost, not an instant answer."""
    if hi <= lo:
        return 0
    lib = _load_lib()
    ctypes.set_errno(0)
    result = int(lib.primesieve_count_primes(lo, hi - 1))
    errno = ctypes.get_errno()
    if errno != 0:
        raise RuntimeError(f"primesieve_count_primes({lo}, {hi - 1}) failed (errno={errno})")
    return result


def nth_prime(n, start=0):
    """The n-th prime AFTER `start` (n must be a positive int) via
    primesieve_nth_prime(n, start) -- e.g. nth_prime(1) == 2, nth_prime(6) == 13.
    start=0 (the default) means 'counting from the very first prime'. See next_prime()/
    prev_prime() below for the signed-n 'search backwards' half of
    primesieve_nth_prime()'s own contract -- kept as separate, differently-named
    functions here rather than exposing the raw signed parameter directly, since a bare
    nth_prime(-5, ...) call reads far less clearly at a GUI call site than prev_prime
    would."""
    if n <= 0:
        raise ValueError("n must be a positive integer")
    lib = _load_lib()
    ctypes.set_errno(0)
    result = int(lib.primesieve_nth_prime(n, start))
    errno = ctypes.get_errno()
    if errno != 0:
        raise RuntimeError(f"primesieve_nth_prime({n}, {start}) failed (errno={errno})")
    return result


def next_prime(x):
    """The smallest prime STRICTLY GREATER than x."""
    return nth_prime(1, x)


def prev_prime(x):
    """The largest prime STRICTLY LESS than x. Raises ValueError for x <= 2 (there is no
    prime below 2) rather than letting libprimesieve's own behavior in that edge case
    leak through silently."""
    if x <= 2:
        raise ValueError("no prime is smaller than 2")
    lib = _load_lib()
    ctypes.set_errno(0)
    result = int(lib.primesieve_nth_prime(-1, x))
    errno = ctypes.get_errno()
    if errno != 0:
        raise RuntimeError(f"primesieve_nth_prime(-1, {x}) failed (errno={errno})")
    return result


def generate_floor_windows(base_power, target_idx_start, target_idx_count, window_m,
                            write_files=True, portal_folder=None):
    """Primesieve-direct equivalent of prime_sieve_v3.py's main_batch_scanner(): generates
    the SAME combined range [combined_lo, combined_hi) a target_idx_list would cover there,
    but via ONE primesieve_generate_primes() call instead of this project's own batched/
    parallel sieve engine, then splits the sorted result into window_m-sized files exactly
    as main_batch_scanner's own write-tail does, using the IDENTICAL PGS2 write_prime_
    window() format/filename convention -- files this mode writes are fully interchangeable
    with ones any other engine in this folder wrote, and vice versa.

    Clamps combined_hi to primesieve_max_stop() + 1 (i.e. to what primesieve can actually
    generate) when the request would otherwise exceed it -- prints a clear WARNING when this
    happens, explaining the library's uint64 ceiling and that Floor/Range/Exploration mode
    (the other engines in this folder, which have no such ceiling) should be used for
    anything past it. The clamp can leave the LAST window narrower than window_m -- that is
    still written complete for whatever it DOES cover (never anything past combined_hi, so
    never mislabeled) -- find_continuation_target_idx (prime_atlas_v1.py) only ever reads a
    window's offset from its FILENAME, never its content size, so a narrower-than-usual
    final window does not confuse continuation/browsing anywhere else in this application.

    Low floors (base_power < LOW_FLOOR_CUTOFF) are split by REAL floor boundary via
    _low_floor_segments(), same as every other engine in this folder."""
    BASE = 10 ** base_power
    combined_lo = BASE + target_idx_start * window_m
    combined_hi = combined_lo + target_idx_count * window_m

    max_stop = primesieve_max_stop()
    truncated_by_ceiling = (combined_hi - 1) > max_stop
    if truncated_by_ceiling:
        combined_hi = max_stop + 1

    print("=" * 70)
    print(f"[*] PRIME SIEVE -- {VERSION} (primesieve mode: calls libprimesieve's own "
          f"primesieve_generate_primes() directly -- see this file's header for "
          f"attribution/source: github.com/kimwalisch/primesieve, BSD license)")
    print(f"[*] libprimesieve version: {primesieve_lib_version()}")
    print(f"[*] Combined range: [{combined_lo:,}, {combined_hi:,})  "
          f"size={max(0, combined_hi - combined_lo):,}")
    if truncated_by_ceiling:
        print(f"[!] WARNING: requested range extends past libprimesieve's own uint64 "
              f"ceiling (primesieve_get_max_stop() = {max_stop:,}). Result TRUNCATED to "
              f"that limit -- anything above {max_stop:,} was NOT generated this run. Use "
              f"Floor, Range, or Exploration mode instead for numbers past this point -- "
              f"they have no such ceiling, at the cost of being slower than this mode.")
    if not write_files:
        print(f"[*] WRITE_FILES=False -- no PGS2 files will be written this run; only the "
              f"aggregate prime count will be reported.")
    print("=" * 70)

    if combined_hi <= combined_lo:
        print("[*] Nothing to generate (range is empty after the ceiling clamp).")
        write_scan_metrics_handoff(portal_folder, total_primes_found=0, windows_processed=0,
                                    write_files=write_files)
        print("=" * 70)
        return

    t_start = time.perf_counter()
    primes = generate_primes_in_range(combined_lo, combined_hi)
    t_gen = time.perf_counter() - t_start
    print(f"[*] libprimesieve generated {len(primes):,} primes in {t_gen:.2f}s.")

    generated_at = int(time.time())
    total_primes_found = 0
    windows_processed = 0

    low_floor_segments = _low_floor_segments(base_power, combined_lo, combined_hi)
    if low_floor_segments:
        for floor, floor_lo, floor_hi in low_floor_segments:
            lo_i = bisect.bisect_left(primes, floor_lo)
            hi_i = bisect.bisect_left(primes, floor_hi)
            segment = primes[lo_i:hi_i]
            count = len(segment)
            if write_files:
                folder = os.path.join(portal_folder, f"10p{floor}", "source_primes")
                os.makedirs(folder, exist_ok=True)
                path = os.path.join(folder, f"PRIME_WINDOW_10p{floor}_off_0.bin")
                write_prime_window(path, segment, generated_at=generated_at)
            total_primes_found += count
            windows_processed += 1
            print(f"    10p{floor}: {count:,} primes")
        skipped_floor = low_floor_segments[-1][0] + 1
        print(f"[*] Low-floor batch: floor(s) {low_floor_segments[0][0]}-"
              f"{low_floor_segments[-1][0]} written complete -- floor {skipped_floor} would "
              f"be cut off by this batch's range, so it was skipped (not written partially).")
    else:
        floor_folder = os.path.join(portal_folder, f"10p{base_power}", "source_primes")
        if write_files:
            os.makedirs(floor_folder, exist_ok=True)
        window_lo = combined_lo
        while window_lo < combined_hi:
            window_hi = min(window_lo + window_m, combined_hi)
            lo_i = bisect.bisect_left(primes, window_lo)
            hi_i = bisect.bisect_left(primes, window_hi)
            segment = primes[lo_i:hi_i]
            if write_files:
                offset = window_lo - BASE
                target_tag = f"10p{base_power}_off_{format_offset(offset)}"
                path = os.path.join(floor_folder, f"PRIME_WINDOW_{target_tag}.bin")
                write_prime_window(path, segment, generated_at=generated_at)
            total_primes_found += len(segment)
            windows_processed += 1
            window_lo = window_hi

    print(f"\n[*] TOTAL PRIMES FOUND this run: {total_primes_found:,} across "
          f"{windows_processed} window(s)"
          + ("" if write_files else "  (NO FILES WRITTEN -- count-only mode)"))
    write_scan_metrics_handoff(portal_folder, total_primes_found=total_primes_found,
                                windows_processed=windows_processed, write_files=write_files)
    write_benchmark_row(base_power, target_idx_start, target_idx_count, t_gen,
                         total_primes_found, windows_processed, write_files, portal_folder)
    print("=" * 70)


