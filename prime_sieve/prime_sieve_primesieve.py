# ==========================================================================================
# prime_sieve_primesieve.py -- "primesieve mode"
#
# Every OTHER engine in this folder (prime_sieve_v1.py .. v4.py) links a small CUSTOM .c
# wrapper (prime_sieve_engine_v*.c) that calls into libprimesieve's INTERNAL segment-sieving
# functions, wrapped in this project's own parallel batching/orchestration machinery
# (orchestrator_v3.py, orchestrator_loop_v2.py -- workers, batches, a shared mmap buffer).
#
# THIS file is different on purpose: it calls libprimesieve's own PUBLIC, top-level C API
# function -- primesieve_generate_primes() -- DIRECTLY, with no custom engine, no batching,
# no orchestrator in between. primesieve's own segmented-sieve-of-Eratosthenes-plus-wheel-
# factorization implementation is, on its own declared domain (the uint64_t range), about as
# fast as this kind of thing gets -- faster than what this project's own batched engines
# achieve at the same depth, since those pay real overhead (per-batch jump_to() bootstrap
# calls, Python-side ProcessPoolExecutor coordination) that primesieve's own internal
# multi-threading avoids entirely by never leaving C in the first place. The trade a person
# makes by choosing THIS mode over Floor/Range/Exploration is exactly that domain limit: once
# a request would need to go past primesieve_get_max_stop() (2**64 - 1), this mode simply
# cannot follow it there (see generate_floor_windows()'s ceiling-clamp/WARNING) -- the other
# three modes have no such ceiling, at the cost of being slower.
#
# The main thing this file adds beyond calling straight into libprimesieve is mapping its
# result onto this project's own on-disk format and folder layout -- write_prime_window()
# (PGS2), the PRIME_WINDOW_10p{N}_off_{offset}.bin filename convention, and the low-floor
# (0-6) splitting behaviour -- all three duplicated verbatim from prime_sieve_v3.py, so a
# floor generated through this mode is byte-for-byte indistinguishable, from every OTHER
# part of this application's point of view, from one generated by any other engine.
#
# Also exposes a handful of libprimesieve's OTHER public API calls that have nothing to do
# with window generation at all -- count_primes_in_range()/nth_prime()/next_prime()/
# prev_prime() -- used by primesieve_query.py (this same folder), the one-shot CLI PrimeAtlas
# launches for its 'primesieve' calculator sub-tab (Liczby pierwsze -> primesieve). That
# script is the one exception to this folder's "no cross-imports between engine files" rule
# above -- it's not a scanner engine itself, just a thin CLI over this file's own bindings.
#
# ATTRIBUTION: this file calls into libprimesieve, an independent, third-party, open-source
# project by Kim Walisch -- NOT authored by, or part of, this project.
#   Source:  https://github.com/kimwalisch/primesieve
#   License: BSD (see that repository's own LICENSE file for the exact text)
#   This file only binds (via ctypes) to the SYSTEM-installed libprimesieve shared library
#   and calls its public C API (primesieve.h / doc/C_API.md in that repository) -- no
#   primesieve source code is copied into this file or this project.
# ==========================================================================================


