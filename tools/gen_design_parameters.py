HEADER = ("<!-- Generated by tools/gen_design_parameters.py from the code's defaults; do not "
          "edit by hand. -->\n\n")


def _import_app():
    for path in (_REPO_ROOT, os.path.join(_REPO_ROOT, "prime_sieve")):
        if path not in sys.path:
            sys.path.insert(0, path)
    from primeatlas.generation import engine_options, generation_settings
    from primeatlas.visualization.shared import renderer_cli
    return engine_options, generation_settings, renderer_cli


def _cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ").strip()


def _form_type(key, default, engine_options, generation_settings):
    """(type and bounds, owner file) of one Generation form field."""
    if key == "engine":
        return "one of " + ", ".join(engine_options.ENGINES), "engine_options.py"
    if key.endswith("_preset"):
        from primeatlas.generation import engine_presets
        return "one of " + ", ".join(engine_presets.PRESETS), "engine_presets.py"
    if key in engine_options.KNOB_KEYS:
        lowest = 0 if key in engine_options._ZERO_ALLOWED else 1
        highest = engine_options._MAX_VALUES.get(key)
        bounds = f"integer >= {lowest}" + (f", <= {highest:,}" if highest else "")
        return bounds, "engine_options.py"
    if key == "strategy":
        return "one of " + ", ".join(generation_settings._KTUPLE_STRATEGY_KEYS), "generation_settings.py"
    if isinstance(default, bool):
        return "on / off", "generation_settings.py"
    if key == "manual_offsets":
        return "integers, space- or comma-separated", "generation_settings.py"
    if default == "":
        return "integer, blank = auto", "generation_settings.py"
    return "integer", "generation_settings.py"


def _form_default(default):
    if isinstance(default, bool):
        return "on" if default else "off"
    return f"`{default}`" if default != "" else "blank"


def form_page(title, section, intro, labels, engine_options, generation_settings):
    rows = ["| Parameter | Default | Type and bounds | Owner | What it does |",
            "|---|---|---|---|---|"]
    for key, default in generation_settings.DEFAULT_GENERATION_SETTINGS[section].items():
        kind, owner = _form_type(key, default, engine_options, generation_settings)
        label = labels.get(FORM_LABELS[section].get(key, ""), "")
        rows.append(f"| `{key}` | {_form_default(default)} | {_cell(kind)} | `{owner}` | "
                    f"{_cell(label) or '(no form label)'} |")
    return (HEADER + f"# Parameters: {title}\n\n{intro}. Remembered per install in "
            "`ui_state.json` (data.md); a key missing there takes the default "
            "below. \"What it does\" is the form's own label.\n\n" + "\n".join(rows) + "\n")


def _arg_type(action):
    if action.choices:
        return "one of " + ", ".join(str(c) for c in action.choices)
    if action.nargs == 0:
        return "flag"
    kind = getattr(action.type, "__name__", None) if action.type else "str"
    return {"int": "integer", "float": "number", "str": "text",
            "parse_big_int": "big integer (digits, a*10**b, a*10^b, aEb)"}.get(kind, kind)


def renderer_page(renderer_cli):
    parser = renderer_cli.build_parser()
    rows = ["| Parameter | Default | Type and bounds | Owner | What it does |",
            "|---|---|---|---|---|"]
    for action in parser._actions:
        if not action.option_strings or action.dest == "help":
            continue
        default = "off" if action.nargs == 0 and action.default is False else (
            "none" if action.default is None else f"`{action.default}`")
        rows.append(f"| `{action.option_strings[0]}` | {_cell(default)} | {_cell(_arg_type(action))} | "
                    f"`renderer_cli.py` | {_cell(action.help or '') or '(no help text)'} |")
    return (HEADER + "# Parameters: visualization-renderer\n\nThe command line of "
            "`primeatlas/visualization/shared/renderer.py` (Rings, Tree, Sphere and Assembly "
            "sub-tabs launch it; each mode adds its own arguments through "
            "`VizMode.add_arguments`). The sub-tabs persist their last values in "
            "`app_settings.json` (data.md). \"What it does\" is the argparse help text.\n\n"
            + "\n".join(rows) + "\n")


def build_pages():
    engine_options, generation_settings, renderer_cli = _import_app()
    with open(LOCALE_EN, encoding="utf-8") as f:
        labels = json.load(f)
    pages = {}
    counts = {}
    for name, section, intro in FORM_AREAS:
        pages[f"{name}.md"] = form_page(name, section, intro, labels, engine_options,
                                        generation_settings)
        counts[name] = len(generation_settings.DEFAULT_GENERATION_SETTINGS[section])
    pages["visualization-renderer.md"] = renderer_page(renderer_cli)
    counts["visualization-renderer"] = pages["visualization-renderer.md"].count("\n| `")
    index = ["| Area | Parameters |", "|---|---|"]
    index += [f"| [{name}]({name}.md) | {count} |" for name, count in counts.items()]
    pages["README.md"] = (
        HEADER + "# Parameters by area\n\nGenerated by `tools/gen_design_parameters.py` from "
        "the defaults the code holds (the Generation form defaults and the visualization "
        "renderer's argparse definitions); do not edit by hand. "
        "`unitTests/test_design_parameters.py` fails when these pages are not current.\n\n"
        "One page per area, `<area>.md`, with the columns Parameter, Default, Type and "
        "bounds, Owner, What it does.\n\n" + "\n".join(index) + "\n")
    return pages


def main(argv):
    pages = build_pages()
    stale = []
    for name, text in pages.items():
        path = os.path.join(OUT_DIR, name)
        current = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if current != text:
            stale.append(name)
            if "--check" not in argv:
                os.makedirs(OUT_DIR, exist_ok=True)
                with open(path, "w", encoding="utf-8", newline="\n") as f:
                    f.write(text)
    if "--check" in argv:
        for name in stale:
            print(f"docs/design/parameters/{name} is not current "
                  f"(run python tools/gen_design_parameters.py)")
        return 1 if stale else 0
    print(f"wrote {len(stale)} of {len(pages)} page(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
