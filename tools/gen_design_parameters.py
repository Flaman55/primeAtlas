"""
gen_design_parameters.py -- writes docs/design/parameters/ from the defaults the code holds:

  - generation-loop / -constellation / -ktuple: the Generation tab's form defaults
    (primeatlas/generation/generation_settings.DEFAULT_GENERATION_SETTINGS; engine and
    perf knobs from engine_options.py), described by the form's own English labels;
  - visualization-renderer: every argument of the visualization renderer's command line
    (primeatlas/visualization/shared/renderer_cli.build_parser()), with its argparse
    default, type or choices and help text.

Run from anywhere:
    python tools/gen_design_parameters.py          # rewrite the pages
    python tools/gen_design_parameters.py --check  # exit 1 when a page is not current
unitTests/test_design_parameters.py runs the check.
"""
